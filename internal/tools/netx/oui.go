var ouiTable = buildOUI()

func buildOUI() map[string]string {
	t := map[string]string{}
	for _, line := range strings.Split(ouiData, "\n") {
		name, list, ok := strings.Cut(strings.TrimSpace(line), "|")
		if !ok {
			continue
		}
		for _, o := range strings.Split(list, ",") {
			o = strings.ToUpper(strings.ReplaceAll(strings.TrimSpace(o), " ", ""))
			if len(o) == 6 {
				if _, dup := t[o]; !dup {
					t[o] = name
				}
			}
		}
	}
	return t
}
