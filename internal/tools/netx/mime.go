var (
	mimeByExt = map[string]string{}
	mimeOrder []string
)

func init() {
	for _, l := range strings.Split(mimeData, "\n") {
		e, t, ok := strings.Cut(strings.TrimSpace(l), "|")
		if !ok || strings.HasSuffix(e, "-alt") || strings.HasSuffix(e, "-video") || strings.HasSuffix(e, "-pem") {
			continue
		}
		mimeByExt[e] = t
		mimeOrder = append(mimeOrder, e)
	}
	mimeByExt["ts"] = "video/mp2t"
}
